/// Border radius design tokens for Docora.
/// Never use raw radius values — always use these constants.
abstract final class AppRadius {
  /// 8dp — small chips, tags, badges
  static const double xs = 8;
  /// 12dp — small cards, buttons
  static const double sm = 12;
  /// 16dp — standard cards, inputs
  static const double md = 16;
  /// 20dp — large cards, file tiles
  static const double lg = 20;
  /// 24dp — bottom sheets, dialogs
  static const double xl = 24;
  /// 32dp — full pill / FAB
  static const double xxl = 32;
  /// 100dp — circular elements
  static const double full = 100;
}
